"""Author seamless grass/moss PBR tiles and an editable Blender material study.
blender --background --python scripts/blender/build_ground_cover.py -- <project>
Tiles represent two metres. All textures and runtime bytes come from this source.
"""
import bpy, numpy as np, math, sys, json, zlib, base64
from pathlib import Path
from mathutils import Vector
root=Path(sys.argv[sys.argv.index('--')+1]);out=root/'assets-source/ground-cover';out.mkdir(parents=True,exist_ok=True)
bpy.ops.object.select_all(action='SELECT');bpy.ops.object.delete(use_global=False)
N=512;rng=np.random.default_rng(7851)
yy,xx=np.mgrid[0:N,0:N]
def noise(scale):
 a=rng.random((N,N));f=np.fft.fft2(a);ky,kx=np.meshgrid(np.fft.fftfreq(N),np.fft.fftfreq(N),indexing='ij')
 a=np.fft.ifft2(f*np.exp(-(kx*kx+ky*ky)*scale*scale)).real
 return (a-a.min())/(a.max()-a.min())
def image(name,data,color=True):
 im=bpy.data.images.new(name,width=data.shape[1],height=data.shape[0],alpha=True)
 if not color:im.colorspace_settings.name='Non-Color'
 rgba=np.concatenate((data,np.ones((*data.shape[:2],1))),axis=2).astype(np.float32)
 im.pixels.foreach_set(rgba.ravel());im.filepath_raw=str(out/(name+'.png'));im.file_format='PNG';im.save();im.pack();return im
tiles=[];materials=[]
for kind in ['grass','moss']:
 broad=noise(70);fine=noise(3);height=.1+.12*broad+.06*fine
 rgb=np.empty((N,N,3));rgb[:]=[.23,.30,.105] if kind=='grass' else [.16,.245,.085]
 rgb*= (.75+broad*.40+fine*.18)[...,None]
 # Thousands of tapered leaves lie in different directions in the seamless tile.
 for i in range(14000 if kind=='grass' else 22000):
  x,y=rng.uniform(0,N,2);angle=rng.uniform(0,math.tau);length=rng.uniform(7,34) if kind=='grass' else rng.uniform(2,8)
  tint=np.array([.32,.40,.14] if kind=='grass' else [.23,.34,.105])*rng.uniform(.7,1.35)
  for t in np.linspace(0,1,int(length*1.3)):
   bx=x+math.cos(angle)*length*t;by=y+math.sin(angle)*length*t
   ix=int(bx)%N;iy=int(by)%N;lift=math.sin(t*math.pi)**.7
   rgb[iy,ix]=tint*(.7+.4*lift);height[iy,ix]=max(height[iy,ix],.25+.65*lift)
   if t<.6:rgb[iy,(ix+1)%N]=tint*.70;height[iy,(ix+1)%N]=max(height[iy,(ix+1)%N],.2+.5*lift)
 # Grass is rough; moss cushions scatter the light more evenly.
 rough=np.clip(.77+fine*.18-height*.06,.65,.98)
 dx=(np.roll(height,-1,axis=1)-np.roll(height,1,axis=1))*.65
 dy=(np.roll(height,-1,axis=0)-np.roll(height,1,axis=0))*.65
 normal=np.stack((-dx,-dy,np.ones_like(dx)),axis=2);normal/=np.linalg.norm(normal,axis=2)[...,None];normal=normal*.5+.5
 albedo=image(kind+'-albedo',np.clip(rgb,0,1));norm=image(kind+'-normal',normal,False);roughmap=image(kind+'-roughness',np.repeat(rough[...,None],3,axis=2),False)
 material=bpy.data.materials.new('Asterion '+kind+' - two metre seamless cover');material.use_nodes=True;nt=material.node_tree;p=nt.nodes.get('Principled BSDF')
 for im,socket in [(albedo,'Base Color'),(roughmap,'Roughness')]:
  tex=nt.nodes.new('ShaderNodeTexImage');tex.image=im;nt.links.new(tex.outputs['Color'],p.inputs[socket])
 tex=nt.nodes.new('ShaderNodeTexImage');tex.image=norm;normalnode=nt.nodes.new('ShaderNodeNormalMap');normalnode.inputs['Strength'].default_value=.65;nt.links.new(tex.outputs['Color'],normalnode.inputs['Color']);nt.links.new(normalnode.outputs['Normal'],p.inputs['Normal'])
 materials.append(material);tiles.append((rgb,normal,rough))
 # A small material swatch is deliberately editable in the saved Blender file.
 bpy.ops.mesh.primitive_grid_add(x_subdivisions=64,y_subdivisions=64,size=2,location=((-1.05 if kind=='grass' else 1.05),0,0))
 plane=bpy.context.object;plane.name=kind+' material study';plane.data.materials.append(material)
 for v in plane.data.vertices:v.co.z=.04*math.sin(v.co.x*2)*math.cos(v.co.y*2)
for label,slot in [('albedo',0),('normal',1),('roughness',2)]:
 values=[t[slot] if slot!=2 else np.repeat(t[slot][...,None],3,axis=2) for t in tiles]
 atlas=np.concatenate(values,axis=1);raw=np.rint(np.clip(atlas,0,1)*255).astype(np.uint8)
 # Blender image.pixels are linear for colour; encode colour bytes as sRGB for Three.
 if slot==0:
  atlas=np.where(atlas<=.0031308,atlas*12.92,1.055*np.maximum(atlas,0)**(1/2.4)-.055);raw=np.rint(np.clip(atlas,0,1)*255).astype(np.uint8)
 packed=base64.b64encode(zlib.compress(raw.tobytes(),9)).decode()
 if label=='albedo':packed_values={}
 packed_values[label]=packed
meta={'tileSize':N,'tileMetres':2,'width':N*2,'height':N,'channels':3,'maps':packed_values}
generated=root/'lib/game/generated';imports=[];entries=[]
for label,packed in packed_values.items():
 names=[]
 for i in range(0,len(packed),350000):
  name=f'cover_{label}_{i//350000}';names.append(name);imports.append(f"import {name} from './{name}';")
  (generated/(name+'.ts')).write_text('export default '+json.dumps(packed[i:i+350000])+';\n')
 entries.append(label+':['+','.join(names)+"].join('')")
(generated/'ground-cover.ts').write_text('// Generated by scripts/blender/build_ground_cover.py.\n'+'\n'.join(imports)+'\nexport const groundCover={tileSize:512,tileMetres:2,width:1024,height:512,channels:3,maps:{'+','.join(entries)+'}} as const;\n')
(out/'catalog.json').write_text(json.dumps({'tileMetres':2,'pixelsPerTile':N,'maps':['albedo','normal','roughness'],'authoring':'Original procedural Blender material study; seamless periodic height and leaf detail.'},indent=2))
bpy.ops.object.light_add(type='AREA',location=(0,-1,4));bpy.context.object.data.energy=450;bpy.context.object.data.shape='DISK';bpy.context.object.data.size=4
bpy.ops.object.camera_add(location=(2,-3.5,3.8));camera=bpy.context.object;camera.rotation_euler=(Vector((0,0,0))-camera.location).to_track_quat('-Z','Y').to_euler();camera.data.type='ORTHO';camera.data.ortho_scale=5.1;bpy.context.scene.camera=camera
scene=bpy.context.scene;scene.render.engine='CYCLES';scene.cycles.samples=24;scene.render.resolution_x=1200;scene.render.resolution_y=760;scene.render.resolution_percentage=100;scene.world.color=(.35,.35,.35)
bpy.ops.wm.save_as_mainfile(filepath=str(out/'asterion-ground-cover.blend'))
scene.render.filepath=str(out/'ground-cover-study.png');bpy.ops.render.render(write_still=True)
print('Built seamless Blender grass and moss maps, packed runtime data and editable source.')
