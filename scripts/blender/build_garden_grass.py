"""Build folded garden grass and loose meadow wisps; export editable Blender/GLB/runtime meshes."""
import bpy,math,random,json,zlib,base64,sys,numpy as np
from pathlib import Path
from mathutils import Vector
root=Path(sys.argv[sys.argv.index('--')+1]);out=root/'assets-source/ground-cover';out.mkdir(parents=True,exist_ok=True)
bpy.ops.object.select_all(action='SELECT');bpy.ops.object.delete(use_global=False)
rng=random.Random(91803);assets={};objects=[]
def pack(values,dtype):return base64.b64encode(zlib.compress(np.array(values,dtype=dtype).tobytes(),9)).decode()
for name,number in [('garden',18),('wisps',9)]:
 verts=[];colors=[];faces=[]
 for blade in range(number):
  angle=rng.uniform(0,math.tau);rad=rng.uniform(.025,.18);bx=math.cos(angle)*rad;bz=math.sin(angle)*rad
  height=rng.uniform(.13,.32) if name=='garden' else rng.uniform(.28,.58)
  width=rng.uniform(.004,.009);bend=rng.uniform(.05,.20);turn=angle+rng.uniform(-1,1)
  tint=rng.uniform(.72,1.16);base=len(verts)
  for level in range(4):
   t=level/3;w=width*(1-t)**.65+.00025;cx=bx+math.sin(turn)*bend*t*t;cz=bz+math.cos(turn)*bend*t*t
   for side in [-1,0,1]:
    verts.append((cx+math.cos(turn)*w*side,cz-math.sin(turn)*w*side,height*t+(.004*(1-abs(side))*math.sin(t*math.pi))))
    colors.extend([(.017+.026*t)*tint,(.055+.080*t)*tint,(.016+.025*t)*tint,1])
   if level<3:
    for side in range(2):
     a=base+level*3+side;faces.extend([(a,a+1,a+4),(a,a+4,a+3)])
 mesh=bpy.data.meshes.new(name+' folded blades');mesh.from_pydata(verts,[],faces);mesh.update()
 color=mesh.color_attributes.new(name='Color',type='FLOAT_COLOR',domain='POINT');color.data.foreach_set('color',colors)
 for p in mesh.polygons:p.use_smooth=True
 mat=bpy.data.materials.new(name+' dark living green');mat.use_nodes=True;mat.use_backface_culling=False;nodes=mat.node_tree.nodes;node=nodes.new('ShaderNodeVertexColor');node.layer_name='Color';p=nodes.get('Principled BSDF');p.inputs['Roughness'].default_value=.83;mat.node_tree.links.new(node.outputs['Color'],p.inputs['Base Color']);mesh.materials.append(mat)
 ob=bpy.data.objects.new(name,mesh);bpy.context.collection.objects.link(ob);objects.append(ob)
 # The runtime uses Y up; Blender uses Z up.
 assets[name]={'p':pack([c for x,z,y in verts for c in (x,y,z)],'<f4'),'c':pack([c for i in range(len(verts)) for c in colors[i*4:i*4+3]],'<f4'),'i':pack([c for f in faces for c in f],'<u2'),'triangles':len(faces)}
 bpy.ops.object.select_all(action='DESELECT');ob.select_set(True);bpy.context.view_layer.objects.active=ob
 bpy.ops.export_scene.gltf(filepath=str(out/(name+'-grass.glb')),use_selection=True,export_format='GLB',export_yup=True)
(root/'lib/game/generated/garden-grass.ts').write_text('// Generated by scripts/blender/build_garden_grass.py\nexport const gardenGrassAssets='+json.dumps(assets,separators=(',',':'))+' as const;\n')
# Preview a small uncut garden with mixed heights and a subtle rise.
for ob in objects:ob.hide_render=True
for i in range(1800):
 x=rng.uniform(-3,3);y=rng.uniform(-3,3);m=objects[1 if rng.random()<.18 else 0];ob=bpy.data.objects.new('Garden grass',m.data);bpy.context.collection.objects.link(ob);ob.location=(x,y,.06*math.sin(x*1.4)*math.cos(y));ob.rotation_euler.z=rng.uniform(0,math.tau);s=rng.uniform(.65,1.25);ob.scale=(s,s,s)
bpy.ops.mesh.primitive_grid_add(x_subdivisions=80,y_subdivisions=80,size=6);plane=bpy.context.object
for v in plane.data.vertices:v.co.z=.06*math.sin(v.co.x*1.4)*math.cos(v.co.y)-.025
mat=bpy.data.materials.new('Dark mossy soil');mat.diffuse_color=(.026,.075,.025,1);plane.data.materials.append(mat)
bpy.ops.object.light_add(type='AREA',location=(0,-2,5));bpy.context.object.data.energy=750;bpy.context.object.data.size=5
bpy.ops.object.camera_add(location=(1.2,-3,1.3));cam=bpy.context.object;cam.rotation_euler=(Vector((0,0,.14))-cam.location).to_track_quat('-Z','Y').to_euler();cam.data.lens=36;bpy.context.scene.camera=cam
scene=bpy.context.scene;scene.render.engine='CYCLES';scene.cycles.samples=24;scene.render.resolution_x=1200;scene.render.resolution_y=800;scene.render.resolution_percentage=100;scene.world.color=(.22,.27,.24)
bpy.ops.wm.save_as_mainfile(filepath=str(out/'asterion-garden-grass.blend'))
scene.render.filepath=str(out/'garden-grass-preview.png');bpy.ops.render.render(write_still=True)
print('Built two folded grass varieties, GLBs, runtime geometry and garden preview.')
